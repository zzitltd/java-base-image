COLUMNS = ["vendor", "java", "os", "flavor", "variant", "status", "method", "source", "size_bytes", "size_mb",
           "compressed_bytes", "compressed_mb", "java_home_mb", "os_id", "os_version_id", "os_pretty_name", "libc",
           "libc_version", "java_version", "java_runtime_version", "java_vendor", "java_vm_name", "trivy_os", "trivy_eosl",
           "vuln_critical", "vuln_high", "vuln_medium", "vuln_low", "vuln_unknown", "vuln_total",
           "fixable_critical", "fixable_high", "fixable_medium", "fixable_low", "fixable_unknown", "fixable_total",
           "base_image", "base_digest", "built_at", "build_seconds", "trivy_version", "trivy_db_updated", "note"]


def row_of(d):
    r = {k: d.get(k, "") for k in COLUMNS}
    if d.get("java_home_bytes"):
        r["java_home_mb"] = round(d["java_home_bytes"] / 1e6, 1)
    for k in ("size", "compressed"):
        if d.get(f"{k}_bytes") not in (None, ""):
            r[f"{k}_mb"] = round(d[f"{k}_bytes"] / 1e6, 1)
    for kind in ("vuln", "fixable"):
        sub = d.get(kind) or {}
        if sub:
            for s in SEVERITIES:
                r[f"{kind}_{s}"] = sub.get(s, 0)
            r[f"{kind}_total"] = sum(sub.values())
    if d.get("status"):
        r["status"] = d["status"]
    elif not d.get("build_ok"):
        r["status"], r["note"] = "build-failed", d.get("build_error", "")
    elif not d.get("scan_ok"):
        r["status"] = "scan-failed"
    elif not d.get("probe_ok"):
        m = re.search(r"SIGSEGV|Error occurred[^\n]*|Problematic frame:\s*#\s*[^\n]*", d.get("probe_tail", ""))
        r["status"], r["note"] = "probe-failed", "JVM did not start: " + (m.group(0).strip() if m else "see probe_tail")
    else:
        r["status"] = "ok"
    return r


def sev(r):
    return " | ".join(f"{r[f'vuln_{s}']} ({r[f'fixable_{s}']})" for s in SEVERITIES[:4])


def report(rdir, selected):
    rows = []
    for cell in selected:
        if cell.method == "none":
            rows.append(row_of(dict(vendor=cell.vendor, java=cell.java, os=cell.os, flavor=cell.flavor, variant="",
                                    status="not-available", method="none", note=cell.note)))
            continue
        for variant in cell.variants:
            d = Job(cell, variant, rdir).load() or dict(vendor=cell.vendor, java=cell.java, os=cell.os, flavor=cell.flavor,
                                                        variant=variant, method=cell.method, status="not-built", note=cell.note)
            rows.append(row_of(d))
    with open(rdir / "summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    meta = trivy_meta()
    ok = [r for r in rows if r["status"] == "ok"]
    md = [f"# Java image matrix -- run {rdir.name}", "",
          f"Generated {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC with trivy {meta['trivy_version']}, "
          f"DB {meta['trivy_db_updated']}. Vulnerability columns count trivy findings over OS packages and bundled "
          "Java libraries, all severities, fixed and unfixed; the number in parentheses is the fixable subset. "
          "Size is the uncompressed image on disk, compressed is the registry transfer size. "
          "`base` is the vendor image as published, `updated` has the OS packages upgraded "
          "(for repo installs the OS is upgraded before Java is installed).", "",
          "| Vendor | Java | OS | Flavor | Variant | Method | Size MB | Compressed MB | Java home MB | OS version | libc | Java version | Critical | High | Medium | Low |",
          "|---|---|---|---|---|---|---:|---:|---:|---|---|---|---:|---:|---:|---:|"]
    md += [f"| {r['vendor']} | {r['java']} | {r['os']} | {r['flavor']} | {r['variant']} | {r['method']} | {r['size_mb']} | "
           f"{r['compressed_mb']} | {r['java_home_mb']} | {r['os_pretty_name']} | {r['libc']} {r['libc_version']} | "
           f"{r['java_runtime_version']} | {sev(r)} |" for r in ok]
    other = [r for r in rows if r["status"] != "ok"]
    if other:
        md += ["", "## Not available or not built", "", "| Vendor | Java | OS | Flavor | Variant | Status | Reason |", "|---|---|---|---|---|---|---|"]
        md += [f"| {r['vendor']} | {r['java']} | {r['os']} | {r['flavor']} | {r['variant']} | {r['status']} | {r['note']} |" for r in other]
    (rdir / "report.md").write_text("\n".join(md) + "\n")
    log(f"report: {len(ok)} ok, {len(other)} other rows -> {rdir / 'summary.csv'}")


def baseos(rdir, workers):
    jobs = [Job(c, v, rdir) for c in base_cells() for v in c.variants]
    parallel(pull, {j.cell.image for j in jobs}, 3)
    for j in jobs:
        d = DOCKERFILES / j.cell.name
        d.mkdir(parents=True, exist_ok=True)
        (d / f"{j.variant}.Dockerfile").write_text(dockerfile(j.cell, j.variant, image_user(j.cell.image)))
    parallel(build, jobs, workers)
    parallel(measure, jobs, workers)
    caches = trivy_caches(workers)
    meta = trivy_meta()
    parallel(lambda j: scan(j, meta, caches), jobs, workers)
    rows = [row_of(j.load()) for j in jobs]
    cols = ["os", "variant", "status", "base_image", "size_mb", "compressed_mb", "os_pretty_name", "libc", "libc_version",
            "trivy_os", "vuln_critical", "vuln_high", "vuln_medium", "vuln_low", "fixable_critical", "fixable_high",
            "fixable_medium", "fixable_low", "base_digest", "built_at"]
    with open(rdir / "base-os.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    md = [f"# Base OS images -- run {rdir.name}", "", "| OS | Variant | Size MB | Compressed MB | OS version | libc | Critical | High | Medium | Low |",
          "|---|---|---:|---:|---|---|---:|---:|---:|---:|"]
    md += [f"| {r['os']} | {r['variant']} | {r['size_mb']} | {r['compressed_mb']} | {r['os_pretty_name']} | {r['libc']} {r['libc_version']} | {sev(r)} |"
           for r in rows if r["status"] == "ok"]
    (rdir / "base-os.md").write_text("\n".join(md) + "\n")
    log(f"baseos: {sum(r['status'] == 'ok' for r in rows)}/{len(rows)} ok -> {rdir / 'base-os.csv'}")


MUSL_OS = {"alpine"}
CAVEATS = {
    ("zulu", "alpine"): "Azul pins Alpine 3.23 in the Docker Official Image; community builds have no published end-of-updates dates",
    ("zulu", "debian"): "community builds have no published end-of-updates dates",
    ("zulu", "ubuntu"): "apt repo needs the bz2 index (CDN serves a stale Packages.gz); no published end-of-updates dates",
    ("temurin", "alpine"): "official image lags the quarterly release by 2-5 weeks",
    ("temurin", "ubuntu"): "official image lags the quarterly release by 2-5 weeks",
    ("redhat", "ubi9-minimal"): "builder images bundle Maven and S2I; UBI 9 findings have no fix without a RHEL subscription",
    ("oracle", "oraclelinux"): "GPL OpenJDK images are frozen at the last update before the next feature release",
    ("corretto", "alpine"): "no Corretto JRE on Alpine; OS package updates are the user's job",
    ("corretto", "al2023"): "published image is a repository snapshot; upgrade with --releasever=latest",
}
REC_COLUMNS = ["java", "flavor", "rank", "kind", "vendor", "os", "variant", "method", "source", "size_mb", "compressed_mb",
               "os_pretty_name", "libc", "java_runtime_version", "vuln_critical", "vuln_high", "vuln_medium", "vuln_low",
               "candidates", "caveat"]


def recommend(rdir, top=5):
    rows = [r for r in csv.DictReader(open(rdir / "summary.csv")) if r["status"] == "ok"]
    out, md = [], [f"# Recommended images -- run {rdir.name}", "",
                   "Rule: no critical or high findings; then fewest medium+low findings; then smallest uncompressed size. "
                   "`glibc` rows are the best candidate outside Alpine (musl) for workloads that need glibc. "
                   "Rank 2+ rows are the runners-up under the same rule.", "",
                   "| Java | Flavor | Kind | Vendor | OS | Variant | Method | Size MB | Compressed MB | OS version | Java version | Medium | Low | Caveat |",
                   "|---|---|---|---|---|---|---|---:|---:|---|---|---:|---:|---|"]
    for java in sorted({int(r["java"]) for r in rows}):
        for flavor in ("jdk", "jre"):
            group = [r for r in rows if int(r["java"]) == java and r["flavor"] == flavor]
            ok = sorted((r for r in group if r["vuln_critical"] == "0" and r["vuln_high"] == "0"),
                        key=lambda r: (int(r["vuln_medium"]) + int(r["vuln_low"]), float(r["size_mb"])))
            picks = [("recommended" if i == 0 else "runner-up", i + 1, r) for i, r in enumerate(ok[:top])]
            glibc = next((r for r in ok if r["os"] not in MUSL_OS), None)
            if glibc and glibc is not ok[0]:
                picks.append(("glibc", ok.index(glibc) + 1, glibc))
            for kind, rank, r in picks:
                rec = {k: r.get(k, "") for k in REC_COLUMNS}
                rec.update(java=java, flavor=flavor, rank=rank, kind=kind, candidates=f"{len(ok)}/{len(group)}",
                           caveat=CAVEATS.get((r["vendor"], r["os"]), ""))
                out.append(rec)
                if kind != "runner-up":
                    md.append(f"| {java} | {flavor} | {kind} | {r['vendor']} | {r['os']} | {r['variant']} | {r['method']} | {r['size_mb']} | "
                              f"{r['compressed_mb']} | {r['os_pretty_name']} | {r['java_runtime_version']} | {r['vuln_medium']} | {r['vuln_low']} | {rec['caveat']} |")
            if not ok:
                md.append(f"| {java} | {flavor} | none | | | | | | | | | | | no image without critical/high findings |")
    md += ["", "## Runners-up", "", "| Java | Flavor | Rank | Vendor | OS | Variant | Size MB | Medium | Low | Java version |", "|---|---|---|---|---|---|---:|---:|---:|---|"]
    md += [f"| {r['java']} | {r['flavor']} | {r['rank']} | {r['vendor']} | {r['os']} | {r['variant']} | {r['size_mb']} | "
           f"{r['vuln_medium']} | {r['vuln_low']} | {r['java_runtime_version']} |" for r in out if r["kind"] == "runner-up"]
    with open(rdir / "recommendations.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=REC_COLUMNS)
        w.writeheader()
        w.writerows(out)
    (rdir / "recommendations.md").write_text("\n".join(md) + "\n")
    log(f"recommend: {sum(1 for r in out if r['kind'] == 'recommended')} pairs -> {rdir / 'recommendations.csv'}")


# ---------- cli ----------

def select(args):
    return [c for c in cells()
            if (not args.vendor or c.vendor in args.vendor) and (not args.java or c.java in args.java)
            and (not args.os or c.os in args.os) and (not args.flavor or c.flavor in args.flavor)
            and (not args.method or c.method in args.method)]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("stages", nargs="+", choices=["matrix", "pull", "generate", "build", "measure", "scan", "report", "recommend", "baseos", "all"])
    p.add_argument("--run-id", default=dt.date.today().isoformat(), help="results/<run-id> (default: today)")
    p.add_argument("-j", "--workers", type=int, default=4)
    p.add_argument("--vendor", nargs="*")
    p.add_argument("--java", nargs="*", type=int)
    p.add_argument("--os", nargs="*")
    p.add_argument("--flavor", nargs="*")
    p.add_argument("--variant", nargs="*", choices=["base", "updated"])
    p.add_argument("--method", nargs="*", choices=["official", "repo", "none"])
    p.add_argument("--retry-failed", action="store_true", help="build: only images whose previous build failed")
    args = p.parse_args()
    stages = ["pull", "generate", "build", "measure", "scan", "report", "recommend", "baseos"] if "all" in args.stages else args.stages
    rdir = ROOT / "results" / args.run_id
    selected = select(args)
    buildable = [c for c in selected if c.method != "none"]
    jobs = [Job(c, v, rdir) for c in buildable for v in c.variants if not args.variant or v in args.variant]

    if "matrix" in stages:
        for c in selected:
            print(f"{c.name:34} {c.method:9} {c.image or c.pkg or c.note}")
        print(f"{len(buildable)} buildable cells ({len(jobs)} images), {len(selected) - len(buildable)} not available")
    if "pull" in stages:
        images = sorted({c.base_image for c in buildable})
        log(f"pulling {len(images)} base images")
        parallel(pull, images, min(args.workers, 3))
    if "generate" in stages:
        fetch_keys()
        for j in jobs:
            d = DOCKERFILES / j.cell.name
            d.mkdir(parents=True, exist_ok=True)
            (d / f"{j.variant}.Dockerfile").write_text(dockerfile(j.cell, j.variant, image_user(j.cell.image) if j.cell.method == "official" else ""))
        log(f"generated {len(jobs)} dockerfiles")
    if "build" in stages:
        todo = [j for j in jobs if j.path.exists() and not j.load().get("build_ok")] if args.retry_failed else jobs
        log(f"building {len(todo)} images with {args.workers} workers")
        parallel(build, todo, args.workers)
    if "measure" in stages:
        parallel(measure, jobs, args.workers)
    if "scan" in stages:
        caches = trivy_caches(args.workers)
        meta = trivy_meta()
        parallel(lambda j: scan(j, meta, caches), jobs, args.workers)
    if "report" in stages:
        report(rdir, selected)
    if "recommend" in stages:
        recommend(rdir)
    if "baseos" in stages:
        baseos(rdir, args.workers)


if __name__ == "__main__":
    main()
