ROOT = pathlib.Path(__file__).resolve().parent
DOCKER = shlex.split(os.environ.get("JBI_DOCKER", "docker"))
TRIVY = shlex.split(os.environ.get("JBI_TRIVY", "trivy"))
KEYS = ROOT / "build" / "keys"
TRIVY_CACHE = ROOT / "build" / "trivy-cache"  # one dir per scan worker: trivy locks its cache exclusively
DOCKERFILES = ROOT / "dockerfiles"
SEVERITIES = ["critical", "high", "medium", "low", "unknown"]

UPGRADE = {
    "apk": "apk upgrade --no-cache",
    "apt": "apt-get update && apt-get -y dist-upgrade && apt-get clean && rm -rf /var/lib/apt/lists/*",
    # Amazon Linux 2023 images lock to a repository snapshot; without --releasever=latest nothing is upgraded
    "dnf": "if grep -q '^ID=\"amzn\"' /etc/os-release; then dnf -y --releasever=latest upgrade; else dnf -y upgrade; fi && dnf clean all",
    "microdnf": "microdnf -y upgrade && microdnf clean all",
    "tdnf": "tdnf -y upgrade && tdnf clean all",
}
# Official images do not declare their package manager, so probe for it.
AUTO_UPGRADE = "set -e; " + "; ".join(
    f"{'if' if i == 0 else 'elif'} command -v {'apt-get' if pm == 'apt' else pm} >/dev/null; then {cmd}"
    for i, (pm, cmd) in enumerate(UPGRADE.items())) + "; else echo 'no known package manager' >&2; exit 1; fi"

PROBE = r"""cat /etc/os-release; echo '===JAVA==='
L=""; [ -e /lib/ld-musl-x86_64.so.1 ] && L=musl
if [ -e /lib64/ld-linux-x86-64.so.2 ] || [ -e /lib/x86_64-linux-gnu/libc.so.6 ]; then L="${L:+$L+}glibc"; fi
echo "LIBC=${L:-unknown}"
[ -e /lib/ld-musl-x86_64.so.1 ] && echo "MUSL_VERSION=$(/lib/ld-musl-x86_64.so.1 2>&1 | sed -n 's/^Version //p')"
for LD in /lib64/ld-linux-x86-64.so.2 /lib/x86_64-linux-gnu/ld-linux-x86-64.so.2; do [ -e "$LD" ] && { echo "GLIBC_VERSION=$($LD --version 2>&1 | sed -n '1s/.*version \([0-9.]*[0-9]\).*$/\1/p')"; break; }; done
J=$(command -v java 2>/dev/null || true)
[ -z "$J" ] && [ -n "$JAVA_HOME" ] && J="$JAVA_HOME/bin/java"
[ -x "$J" ] || J=$(find / -type f -name java -path '*/bin/java' 2>/dev/null | head -1)
echo "JAVA_BIN=$J"
if [ -n "$JAVA_HOME" ] && [ -x "$JAVA_HOME/bin/java" ]; then JH=$JAVA_HOME; else JH=$(dirname "$(dirname "$(readlink -f "$J")")"); case "$JH" in */jre) JH=$(dirname "$JH");; esac; fi
JH=$(readlink -f "$JH"); echo "JAVA_HOME_DIR=$JH"; echo "JAVA_HOME_KB=$(du -sk "$JH" 2>/dev/null | cut -f1)"
"$J" -XshowSettings:properties -version 2>&1"""


def log(msg):
    print(f"[{dt.datetime.now():%H:%M:%S}] {msg}", flush=True)


def run(cmd, timeout=None):
    return subprocess.run(cmd, text=True, capture_output=True, timeout=timeout)


def docker(*args, **kw):
    return run(DOCKER + list(args), **kw)


def parallel(fn, items, workers):
    with cf.ThreadPoolExecutor(max_workers=workers) as ex:
        return list(ex.map(fn, items))


# ---------- dockerfiles ----------

def dockerfile(cell, variant, orig_user):
    lines = [f"# generated by jbi.py -- {cell.name}:{variant}", f"FROM {cell.base_image}"]
    if cell.method == "official":
        if variant == "updated":
            lines += ["USER root", f"RUN {AUTO_UPGRADE}"] + ([f"USER {orig_user}"] if orig_user else [])
        return "\n".join(lines) + "\n"
    lines.append(f"RUN {UPGRADE[cell.pm]}")
    if cell.pm == "apt":
        steps = []
        if cell.repo:
            _, line, conf = APT_REPOS[cell.repo]
            lines.append(f"COPY build/keys/{cell.repo}.asc /etc/apt/keyrings/{cell.repo}.asc")
            if conf:
                steps.append(f"printf '{conf}\\n' > /etc/apt/apt.conf.d/99-{cell.repo}")
            steps += ["apt-get update", "apt-get install -y --no-install-recommends ca-certificates",
                      f'echo "deb [signed-by=/etc/apt/keyrings/{cell.repo}.asc] {line.format(codename=OS[cell.os][2])}"'
                      f" > /etc/apt/sources.list.d/{cell.repo}.list"]
        steps += ["apt-get update", f"apt-get install -y --no-install-recommends {cell.pkg}",
                  "apt-get clean && rm -rf /var/lib/apt/lists/*"]
    else:
        steps = []
        if cell.repo:
            name, baseurl, gpgkey = RPM_REPOS[cell.repo]
            steps.append(f"printf '[{cell.repo}]\\nname={name}\\nbaseurl={baseurl}\\nenabled=1\\ngpgcheck=1\\ngpgkey={gpgkey}\\n'"
                         f" > /etc/yum.repos.d/{cell.repo}.repo")
        steps += [f"{cell.pm} -y --setopt=install_weak_deps=0 --nodocs install {cell.pkg}", f"{cell.pm} clean all"]
    lines.append("RUN " + " \\\n && ".join(steps))
    return "\n".join(lines) + "\n"


def fetch_keys():
    KEYS.mkdir(parents=True, exist_ok=True)
    for name, (url, _, _) in APT_REPOS.items():
        dest = KEYS / f"{name}.asc"
        if not dest.exists():
            data = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "curl/8"}), timeout=60).read()
            if not data.startswith(b"-----BEGIN PGP"):
                raise SystemExit(f"{url}: expected an ASCII-armored key")
            dest.write_bytes(data)


def image_user(image):
    r = docker("image", "inspect", "--format", "{{.Config.User}}", image)
    return r.stdout.strip() if r.returncode == 0 else ""


def pull(image, retries=12, wait=600):
    for attempt in range(retries):
        r = docker("pull", "--platform", "linux/amd64", "-q", image, timeout=1800)
        if r.returncode == 0:
            return True
        if "toomanyrequests" in r.stderr or "rate limit" in r.stderr.lower():
            log(f"pull {image}: rate limited, waiting {wait}s ({attempt + 1}/{retries})")
            time.sleep(wait)
            continue
        log(f"pull {image} FAILED: {(r.stderr.strip().splitlines() or [r.stdout])[-1]}")
        return False
    return False


# ---------- per-image work ----------

class Job:
    def __init__(self, cell, variant, rdir):
        self.cell, self.variant, self.rdir = cell, variant, rdir
        self.tag = cell.tag(variant)
        self.key = f"{cell.name}-{variant}"
        self.path = rdir / "images" / f"{self.key}.json"

    def load(self):
        return json.loads(self.path.read_text()) if self.path.exists() else {}

    def save(self, **fields):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        d = self.load()
        d.update(fields)
        self.path.write_text(json.dumps(d, indent=1, sort_keys=True))
        return d


def build(job):
    c = job.cell
    df = DOCKERFILES / c.name / f"{job.variant}.Dockerfile"
    logf = job.rdir / "logs" / f"{job.key}.build.log"
    logf.parent.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    r = docker("build", "--no-cache", "--platform", "linux/amd64", "-f", str(df), "-t", job.tag, str(ROOT), timeout=3600)
    logf.write_text(r.stdout + r.stderr)
    ok = r.returncode == 0
    job.save(vendor=c.vendor, java=c.java, os=c.os, flavor=c.flavor, variant=job.variant, method=c.method,
             source=c.image or (f"{c.repo}:{c.pkg}" if c.repo else c.pkg), note=c.note, base_image=c.base_image,
             tag=job.tag, build_ok=ok, build_seconds=round(time.time() - t0),
             built_at=dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
             build_error="" if ok else (r.stderr.strip().splitlines() or ["?"])[-1][:300])
    log(f"build {job.tag}: {'ok' if ok else 'FAILED'} ({round(time.time() - t0)}s)")
    return ok


_STORE = {}


def containerd_store():
    if "containerd" not in _STORE:
        _STORE["containerd"] = "io.containerd.snapshotter" in docker("info", "--format", "{{json .DriverStatus}}").stdout
    return _STORE["containerd"]


def measure(job):
    if not job.load().get("build_ok"):
        return False
    r = docker("history", "--human=false", "--format", "{{.Size}}", job.tag)
    size = sum(int(x) for x in r.stdout.split()) if r.returncode == 0 else None
    r = docker("image", "inspect", "--format", "{{.Size}}", job.tag)
    # the containerd image store reports compressed + uncompressed as .Size; the classic store reports uncompressed only
    compressed = int(r.stdout.strip()) - size if r.returncode == 0 and size is not None and containerd_store() else None
    r = docker("image", "inspect", "--format", "{{index .RepoDigests 0}}", job.cell.base_image)
    digest = r.stdout.strip() if r.returncode == 0 else ""
    r = docker("run", "--rm", "--platform", "linux/amd64", "--user", "0", "--entrypoint", "/bin/sh", job.tag, "-c", PROBE, timeout=300)
    out = r.stdout + r.stderr
    osrel, _, javaout = out.partition("===JAVA===")
    osr = dict(re.findall(r'^(\w+)="?([^"\n]*)"?$', osrel, re.M))
    kv = dict(re.findall(r"^(LIBC|MUSL_VERSION|GLIBC_VERSION|JAVA_BIN|JAVA_HOME_DIR|JAVA_HOME_KB)=(.*)$", javaout, re.M))
    props = {m.group(1): m.group(2).strip() for m in re.finditer(r"^\s+([\w.]+) = (.*)$", javaout, re.M)}
    ver = re.search(r'(?:openjdk|java) version "([^"]+)"', javaout)
    job.save(size_bytes=size, compressed_bytes=compressed, base_digest=digest,
             libc=kv.get("LIBC", ""), libc_version=" / ".join(v for v in (kv.get("MUSL_VERSION"), kv.get("GLIBC_VERSION")) if v),
             os_id=osr.get("ID", ""), os_version_id=osr.get("VERSION_ID", ""), os_pretty_name=osr.get("PRETTY_NAME", ""),
             java_bin=kv.get("JAVA_BIN", ""), java_home=kv.get("JAVA_HOME_DIR", ""),
             java_home_bytes=int(kv["JAVA_HOME_KB"]) * 1024 if kv.get("JAVA_HOME_KB", "").isdigit() else None,
             java_version=ver.group(1) if ver else "", java_runtime_version=props.get("java.runtime.version", ""),
             java_vendor=props.get("java.vendor", ""), java_vendor_version=props.get("java.vendor.version", ""),
             java_vm_name=props.get("java.vm.name", ""),
             probe_ok=bool(props) or (job.cell.java == 0 and bool(osr)), probe_tail="" if props else javaout[-500:])
    log(f"measure {job.tag}: {osr.get('PRETTY_NAME', '?')} / {props.get('java.runtime.version', '-')} / {size}")
    return True


def trivy(cache, *args, **kw):
    return run(TRIVY + ["--cache-dir", str(cache)] + list(args), **kw)


def trivy_caches(n):
    caches = [TRIVY_CACHE / str(i) for i in range(n)]

    def prep(c):
        c.mkdir(parents=True, exist_ok=True)
        for flag in ("--download-db-only", "--download-java-db-only"):
            r = trivy(c, "image", flag, timeout=1800)
            if r.returncode:
                raise SystemExit(f"trivy {flag} into {c} failed: {r.stderr[-500:]}")
    parallel(prep, caches, n)
    q = queue.Queue()
    for c in caches:
        q.put(c)
    return q


def trivy_meta():
    r = trivy(TRIVY_CACHE / "0", "version", "--format", "json")
    j = json.loads(r.stdout) if r.returncode == 0 else {}
    return {"trivy_version": j.get("Version", ""), "trivy_db_updated": (j.get("VulnerabilityDB") or {}).get("UpdatedAt", "")}


def scan(job, meta, caches):
    if not job.load().get("build_ok"):
        return False
    out = job.rdir / "trivy" / f"{job.key}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    cache = caches.get()
    try:
        r = trivy(cache, "image", "--quiet", "--skip-db-update", "--skip-java-db-update", "--scanners", "vuln",
                  "--format", "json", "--output", str(out), job.tag, timeout=1800)
    finally:
        caches.put(cache)
    if r.returncode != 0:
        job.save(scan_ok=False, scan_error=r.stderr.strip()[-300:])
        log(f"scan {job.tag}: FAILED")
        return False
    j = json.loads(out.read_text())
    counts, fixable = dict.fromkeys(SEVERITIES, 0), dict.fromkeys(SEVERITIES, 0)
    for res in j.get("Results") or []:
        for v in res.get("Vulnerabilities") or []:
            s = v.get("Severity", "UNKNOWN").lower()
            counts[s] = counts.get(s, 0) + 1
            if v.get("FixedVersion"):
                fixable[s] = fixable.get(s, 0) + 1
    md = j.get("Metadata", {}).get("OS", {}) or {}
    job.save(scan_ok=True, vuln=counts, fixable=fixable, trivy_os=f"{md.get('Family', '')} {md.get('Name', '')}".strip(),
             trivy_eosl=bool(md.get("EOSL")), **meta)
    log(f"scan {job.tag}: C{counts['critical']} H{counts['high']} M{counts['medium']} L{counts['low']}")
    return True


